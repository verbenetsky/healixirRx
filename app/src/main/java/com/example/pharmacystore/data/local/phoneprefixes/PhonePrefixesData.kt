    /** Generates the flag emoji from its ISO alpha‑2 code. */
    fun isoToEmoji(iso: String): String {
        val base = 0x1F1E6      // U+1F1E6 = 🇦  (regional indicator A)
        val sb   = StringBuilder(2)

        iso.uppercase(Locale.ROOT).forEach { ch ->
            val codePoint = base + (ch.code - 'A'.code)
            sb.appendCodePoint(codePoint)        // ← dodaje parę surrogate’ów
        }
        return sb.toString()                     // np. "🇵🇱"
    }

    /** Returns list of country names paired with their flag emoji. */
    fun withEmoji(): List<Pair<String, String>> =
        listOfPrefixes.map { cp -> cp.name to isoToEmoji(cp.isoAlpha2) }
}
